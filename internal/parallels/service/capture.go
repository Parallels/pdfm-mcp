package service

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"time"

	"github.com/Parallels/pdfm-mcp/internal/parallels/interfaces"
)

const (
	// captureTimeout bounds one screenshot; it should take well under a
	// second. It is shorter than the power cap on purpose.
	captureTimeout = 30 * time.Second
	// maxCaptureBytes bounds the PNG we are willing to load into memory.
	maxCaptureBytes = 32 << 20 // 32 MB
)

var pngMagic = []byte{0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n'}

// Capture takes a screenshot of the VM identified by vmRef (id or name).
// prlctl can only write to a file, so Capture creates a private temp
// directory (0700), hands prlctl a path inside it, reads the bytes, and
// removes the directory on every path (success, error, timeout, cancel).
// It does not change VM state and does not touch the VM list cache.
func (s *service) Capture(ctx context.Context, vmRef string) (interfaces.CaptureResult, error) {
	if !s.enabled {
		return interfaces.CaptureResult{}, ErrNotEnabled
	}
	ref, err := ValidateVMRef(vmRef)
	if err != nil {
		return interfaces.CaptureResult{}, err
	}

	dir, err := os.MkdirTemp("", "pdfm-mcp-capture-")
	if err != nil {
		return interfaces.CaptureResult{}, fmt.Errorf("create capture temp dir: %w", err)
	}
	defer func() {
		if rerr := os.RemoveAll(dir); rerr != nil {
			s.logger.Warn("could not remove capture temp dir", "dir", dir, "err", rerr)
		}
	}()
	file := filepath.Join(dir, "capture.png")

	runCtx, cancel := context.WithTimeout(ctx, captureTimeout)
	defer cancel()

	start := time.Now()
	// argv: capture <vm> --file <generated path>. No shell, single elements.
	// The runner's stdout is ignored (prlctl prints nothing useful) and is
	// never inherited (stdout rule).
	if _, err := s.runner.Run(runCtx, s.prlctlPath, "capture", ref, "--file", file); err != nil {
		s.logger.Warn("prlctl capture failed", "vm", ref, "err", err)
		return interfaces.CaptureResult{}, err
	}

	png, err := readCapture(file)
	if err != nil {
		return interfaces.CaptureResult{}, err
	}
	s.logger.Info("prlctl capture completed", "vm", ref, "bytes", len(png), "took", time.Since(start))
	return interfaces.CaptureResult{PNG: png, CapturedAt: time.Now().UTC()}, nil
}

// readCapture loads the file prlctl wrote, with size and format checks.
func readCapture(path string) ([]byte, error) {
	f, err := os.Open(path) // #nosec G304 -- path is generated by Capture inside its own private temp dir
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, errors.New("prlctl capture reported success but produced no file (is the VM running?)")
		}
		return nil, fmt.Errorf("open capture: %w", err)
	}

	// Read at most max+1 bytes so an oversized file is detected without
	// loading it all.
	var data []byte
	data, err = io.ReadAll(io.LimitReader(f, maxCaptureBytes+1))
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return nil, fmt.Errorf("read capture: %w", err)
	}
	if len(data) > maxCaptureBytes {
		return nil, fmt.Errorf("capture is larger than %d bytes", maxCaptureBytes)
	}
	if len(data) == 0 {
		return nil, errors.New("capture file is empty")
	}
	if !bytes.HasPrefix(data, pngMagic) {
		return nil, errors.New("capture file is not a PNG")
	}
	return data, nil
}
